def test_globs_cross_directories_and_match_basenames() -> None:
    assert glob_regex("**/app.dylib").match("Contents/MacOS/app.dylib")
    assert glob_regex("**/app.dylib").match("app.dylib")
    assert not glob_regex("Contents/*.dylib").match("Contents/MacOS/app.dylib")
    assert path_matches("Contents/MacOS/core.dylib", ["core*"])
    assert not path_matches("Contents/MacOS/core.dylib", ["Contents/core*"])


def test_annotation_keeps_line_count_and_skips_comments_and_strings(
    tmp_path: Path,
) -> None:
    path = tmp_path / "a.c"
    original = "\n".join(
        [
            "/* metadata:",
            " * foo here is a comment",
            " */",
            "int f(void) {",
            '  puts("foo");',
            "  return foo(1);",
            "}",
            "",
        ]
    )
    path.write_text(original)
    note = Annotation("a.c", 1, 7, ["foo"], "foo -> lib.so/src/raw/b.c:3-9")

    assert annotate_file(path, [note]) == 1
    lines = path.read_text().split("\n")
    assert len(lines) == len(original.split("\n"))
    assert (
        lines[5] == "  return foo(1); /* tocode-link: foo -> lib.so/src/raw/b.c:3-9 */"
    )
    assert lines[4] == '  puts("foo");' and lines[1] == " * foo here is a comment"

    # Idempotent, and a call that cannot be found goes into the metadata line.
    assert annotate_file(path, [note]) == 1
    assert path.read_text().count("tocode-link") == 1
    other = Annotation("a.c", 1, 7, ["missing"], "missing -> x")
    annotate_file(path, [other])
    text = path.read_text().split("\n")
    assert text[0] == "/* metadata: tocode-link: missing -> x"
    assert "tocode-link" not in text[5]
    assert strip_annotations(text[0]) == "/* metadata:"
