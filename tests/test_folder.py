def _app(root: Path) -> Path:
    write(
        root / "bin/app",
        elf(
            executable=True,
            needed=["libfoo.so.1", "libbar.so"],
            rpath="$ORIGIN/../lib",
            imports=[("foo_add", "FOO_1.0", "libfoo.so.1"), ("bar_mul", None, None)],
        ),
    )
    write(
        root / "lib/libfoo.so.1",
        elf(soname="libfoo.so.1", exports=[("foo_add", 0x700, "FOO_1.0")]),
    )
    write(
        root / "lib/libbar.so",
        elf(soname="libbar.so", exports=[("bar_mul", 0x500, None)]),
    )
    write(root / "lib/libstdc++.so.6", elf(soname="libstdc++.so.6"))
    write(root / "README.txt", b"not a binary\n", 0o644)
    return root


class FakeExporter:
    """Writes the files a real export leaves, from the binary's link facts."""

    def __init__(self, fail: set[str] | None = None) -> None:
        self.calls: list[str] = []
        self.fail = fail or set()

    def __call__(
        self, lib: NativeLib, out_dir: Path, progress: Progress
    ) -> tuple[str, str, int, int]:
        from tocode.errors import ToCodeError
        from tocode.links.extract import read_facts
        from tocode.links.sniff import classify

        self.calls.append(lib.entry)
        if lib.entry in self.fail:
            raise ToCodeError("backend crashed")
        facts = read_facts(lib.path, lib.entry, classify(lib.path).kind)[0]
        out_dir.mkdir(parents=True, exist_ok=True)
        source = ["/* Generated by ToCode. */"]
        rows: list[dict[str, Any]] = []
        for export in facts.exports:
            start = len(source) + 1
            source += [
                "/* metadata:",
                " */",
                f"int {export.name}(int a) {{",
                "  return a;",
                "}",
            ]
            rows.append(
                self._row(export.address or 0, export.name, start, len(source), [])
            )
        if facts.kind == "executable":
            start = len(source) + 1
            names = [item.name for item in facts.imports]
            calls = [
                f"  x = {item.name}__{item.version.replace('.', '_')}(x);"
                if item.version
                else f"  x = {item.name}(x);"
                for item in facts.imports
            ]
            source += [
                "/* metadata:",
                " */",
                "int main(int x) {",
                *calls,
                "  return x;",
                "}",
            ]
            rows.append(self._row(0x900, "main", start, len(source), names))
        (out_dir / "src/raw").mkdir(parents=True, exist_ok=True)
        (out_dir / "src/raw/a.c").write_text("\n".join(source) + "\n")
        (out_dir / "functions.json").write_text(json.dumps({"functions": rows}))
        (out_dir / "imports.json").write_text(
            json.dumps(
                {
                    "imports": [
                        {
                            "dll": "x",
                            "functions": [
                                {"name": item.name, "address": "0x0"}
                                for item in facts.imports
                            ],
                        }
                    ]
                }
            )
        )
        (out_dir / "exports.json").write_text(
            json.dumps({"exports": [{"name": item.name} for item in facts.exports]})
        )
        (out_dir / "project.json").write_text(json.dumps({"image_base": "0x0"}))
        (out_dir / "export-manifest.json").write_text("{}")
        return ("fake", "fake", len(rows), 0)

    @staticmethod
    def _row(
        address: int, name: str, start: int, end: int, imports: list[str]
    ) -> dict[str, Any]:
        return {
            "address": f"0x{address:x}",
            "name": name,
            "size": 0x10,
            "callees": [],
            "callees_imports": imports,
            "source_file": "src/raw/a.c",
            "source_line_start": start,
            "source_line_end": end,
            "asm_file": "src/raw/a.asm",
            "asm_line_start": 1,
            "asm_line_end": 2,
        }


def _export(root: Path, tmp_path: Path, exporter: FakeExporter, **kwargs: Any):
    options = FolderOptions(out_dir=tmp_path / "out", **kwargs)
    return export_folder(
        root, options=options, progress=Progress(enabled=False), exporter=exporter
    )


def test_folder_export_links_exports_and_annotates(tmp_path: Path) -> None:
    root = _app(tmp_path / "app")
    exporter = FakeExporter()

    summary = _export(root, tmp_path, exporter)

    # Executable first, then what it loads; the bundled libstdc++ is skipped.
    assert exporter.calls == ["bin/app", "lib/libfoo.so.1", "lib/libbar.so"]
    statuses = {job.relpath: job.status for job in summary.jobs}
    assert statuses["lib/libstdc++.so.6"] == RUNTIME
    out = tmp_path / "out"
    mappings = json.loads((out / "mappings.json").read_text())
    by_symbol = {row["symbol"]: row for row in mappings["links"]}
    foo = by_symbol["foo_add"]
    assert foo["target_function"]["source_file"] == "lib/libfoo.so.1/src/raw/a.c"
    assert foo["call_sites"][0]["name"] == "main"
    source = (out / "bin/app/src/raw/a.c").read_text()
    assert (
        "x = foo_add__FOO_1_0(x); /* tocode-link: foo_add -> lib/libfoo.so.1/src/raw/a.c:2-6 */"
        in source
    )
    functions = json.loads((out / "lib/libbar.so/functions.json").read_text())[
        "functions"
    ]
    assert functions[0]["imported_by_count"] == 1
    imports = json.loads((out / "bin/app/imports.json").read_text())
    assert {edge["library"] for edge in imports["libraries"]} == {
        "libfoo.so.1",
        "libbar.so",
    }
    for name in (
        "AGENTS.md",
        "CLAUDE.md",
        "project.json",
        "inventory.json",
        "dependency-graph.json",
        "export-manifest.json",
    ):
        assert (out / name).is_file()
    assert json.loads((out / "project.json").read_text())["kind"] == "folder"
    agents = out / "bin/app/AGENTS.md"
    assert not agents.exists()  # written by the real exporter, not the fake


def test_folder_export_resumes_and_relinks_idempotently(tmp_path: Path) -> None:
    root = _app(tmp_path / "app")
    _export(root, tmp_path, FakeExporter())
    source = tmp_path / "out/bin/app/src/raw/a.c"
    first = source.read_text()

    again = FakeExporter()
    summary = _export(root, tmp_path, again)

    assert again.calls == []  # unchanged binaries are not exported again
    assert all(job.reused for job in summary.jobs if job.status == DONE)
    assert source.read_text() == first

    # A changed binary gets a new job key and is exported again.
    write(
        root / "lib/libbar.so",
        elf(soname="libbar.so", exports=[("bar_mul", 0x540, None)]),
    )
    changed = FakeExporter()
    _export(root, tmp_path, changed)
    assert changed.calls == ["lib/libbar.so"]


def test_folder_export_filters_and_failures(tmp_path: Path) -> None:
    root = _app(tmp_path / "app")
    exporter = FakeExporter(fail={"lib/libfoo.so.1"})

    summary = _export(root, tmp_path, exporter, exclude=["libbar*"])

    statuses = {job.relpath: job.status for job in summary.jobs}
    assert statuses["lib/libbar.so"] == FILTERED
    assert statuses["lib/libfoo.so.1"].startswith("failed")
    assert statuses["bin/app"] == DONE  # one failure does not stop the run
    mappings = json.loads((tmp_path / "out/mappings.json").read_text())
    bar = next(row for row in mappings["links"] if row["symbol"] == "bar_mul")
    assert bar["target"] == "lib/libbar.so" and bar["target_status"] == FILTERED


def test_links_only_does_not_export(tmp_path: Path) -> None:
    root = _app(tmp_path / "app")
    exporter = FakeExporter()

    _export(root, tmp_path, exporter, links_only=True)

    assert exporter.calls == []
    assert (tmp_path / "out/mappings.json").is_file()


def test_plan_writes_nothing(tmp_path: Path) -> None:
    root = _app(tmp_path / "app")

    summary = _export(root, tmp_path, FakeExporter(), plan=True)

    assert not (tmp_path / "out").exists()
    text = format_plan(summary)
    assert "1. bin/app" in text and "lib/libfoo.so.1" in text


def test_output_inside_the_input_must_be_a_decompiled_folder(tmp_path: Path) -> None:
    from tocode.errors import ToCodeError

    root = _app(tmp_path / "app")
    with pytest.raises(ToCodeError, match="inside the input folder"):
        export_folder(
            root, options=FolderOptions(out_dir=root / "out"), exporter=FakeExporter()
        )


def test_scan_skips_our_own_outputs(tmp_path: Path) -> None:
    root = _app(tmp_path / "app")
    write(root / "app_decompiled/bin/app/x.so", elf(soname="x.so"))

    inventory = scan(root)

    assert all(
        not entry.relpath.startswith("app_decompiled") for entry in inventory.entries
    )


def test_pe_duplicate_files_export_once(tmp_path: Path) -> None:
    root = tmp_path / "w"
    data = pe(name="a.dll", exports=[("f", 1, 0x1000)])
    write(root / "a.dll", data)
    write(root / "copy/a.dll", data)
    exporter = FakeExporter()

    summary = _export(root, tmp_path, exporter)

    assert exporter.calls == ["a.dll"]
    duplicate = next(job for job in summary.jobs if job.relpath == "copy/a.dll")
    assert duplicate.status == "duplicate of a.dll"


